package com.wildlife.model.enums;

/**
 * Mùa trong năm, ảnh hưởng tới sự phát triển của thực vật
 * và chỉ số sinh tồn của động vật.
 */
public enum Season {
    SPRING,     // Cây cối phát triển mạnh, động vật dễ sinh sản
    SUMMER,     // Cây cối bình thường, khát nước nhanh hơn
    AUTUMN,     // Cây cỏ rụng lá, thức ăn khan hiếm dần
    WINTER      // Lạnh, động vật mất máu nếu ở ngoài trời quá lâu, thức ăn hiếm
}
